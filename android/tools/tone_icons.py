#!/usr/bin/env python3
"""
Make the "Match my accent color" launcher icons: Material You's tonal style (a light tone of a hue behind a
deep tone of it, or the other way round for dark) in 18 hues, each an adaptive icon with its own
activity-alias. Android only lets an app switch between icons it ships, so Nova picks the nearest of these
to your accent color. Run from android/:  python3 tools/tone_icons.py
"""
import colorsys, os, re

RES = "app/src/main/res"
HUES = list(range(0, 360, 20))
MODES = {"l": ((.55, .88), (.60, .30)), "d": ((.35, .17), (.70, .80))}      # (bg sat, light), (fg sat, light)

def hexc(h, s, l):
    r, g, b = colorsys.hls_to_rgb(h / 360, l, s)
    return "#FF%02X%02X%02X" % (round(r * 255), round(g * 255), round(b * 255))

fg_src = open(f"{RES}/drawable/ic_launcher_fg_material.xml").read()
names = []
for m, ((bs, bl), (fs, fl)) in MODES.items():
    for h in HUES:
        n = f"tone_{m}{h:03d}"; names.append((n, h, m, hexc(h, bs, bl), hexc(h, fs, fl)))
        bg, fg = names[-1][3], names[-1][4]
        open(f"{RES}/drawable/ic_launcher_bg_{n}.xml", "w").write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- generated by tools/tone_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="{bg}" android:pathData="M0,0h108v108h-108z" />
</vector>
''')
        # the symbol in the deep tone, its cut-outs (white in the Material icon) in the background tone
        f = fg_src.replace('fillColor="#FF2F4A8F"', f'fillColor="{fg}"').replace('fillColor="#FFFFFFFF"', f'fillColor="{bg}"')
        open(f"{RES}/drawable/ic_launcher_fg_{n}.xml", "w").write(f.replace("generated: app icon variant", "generated by tools/tone_icons.py"))
        open(f"{RES}/mipmap-anydpi-v26/ic_launcher_{n}.xml", "w").write(f'''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_bg_{n}" />
    <foreground android:drawable="@drawable/ic_launcher_fg_{n}" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''')

# activity-aliases between the markers in the manifest
man = "app/src/main/AndroidManifest.xml"; s = open(man).read()
block = "".join(f'''        <activity-alias android:name=".IconT{n[5:]}" android:targetActivity=".MainActivity" android:exported="true" android:enabled="false"
            android:icon="@mipmap/ic_launcher_{n}" android:roundIcon="@mipmap/ic_launcher_{n}">
            <intent-filter><action android:name="android.intent.action.MAIN" /><category android:name="android.intent.category.LAUNCHER" /></intent-filter>
        </activity-alias>
''' for n, *_ in names)
a, b = "        <!-- tone icons (tools/tone_icons.py) -->\n", "        <!-- /tone icons -->\n"
if a in s: s = s[:s.index(a) + len(a)] + block + s[s.index(b):]
else: s = s.replace("    </application>", a + block + b + "    </application>")
open(man, "w").write(s)

# the Kotlin table: id, alias, background color
kt = "app/src/main/java/app/novalabs/nova/ToneIcons.kt"
rows = ",\n".join(f'    ToneIcon("{n}", ".IconT{n[5:]}", R.mipmap.ic_launcher_{n}, {h}, "{m}", 0x{bg[1:]}.toInt(), 0x{fg[1:]}.toInt())' for n, h, m, bg, fg in names)
open(kt, "w").write(f'''package app.novalabs.nova

// generated by tools/tone_icons.py — Material You tonal launcher icons in 18 hues, light and dark
data class ToneIcon(val id: String, val cls: String, val res: Int, val hue: Int, val mode: String, val bg: Int, val fg: Int)

val TONE_ICONS = listOf(
{rows}
)
''')
print(len(names), "icons")
